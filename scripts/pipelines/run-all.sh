#!/bin/bash
# run-all.sh — the ONE command: scan the six portals → score vs your CV → tailor résumés →
# build the master workbook. Run from the repo root:  bash run-all.sh
#
# Portal set (per user 2026-07-23, six only): LinkedIn, Naukri, Google, Indeed,
# Hirist, Instahyre. Each scanner is best-effort — a wall on one never stops the rest.

cd "$(cd "$(dirname "$0")/../.." && pwd)" || exit 1
NODE="${NODE:-node}"
CAP="${1:-}"   # optional: cap new jobs per board, e.g.  bash run-all.sh 15

run() { echo "── $*"; $NODE "$@" $CAP 2>&1 | tail -2; echo; }

echo "===== SCAN — 6 portals ====="
# real browser, no login, headless
run scripts/scan/scan-devops.mjs
run scripts/scan/scan-google.mjs --headless
run scripts/scan/scan-indeed.mjs --headless
# real browser + your session, headless
run scripts/scan/scan-naukri.mjs --headless
run scripts/scan/scan-hirist.mjs --headless
run scripts/scan/scan-instahyre.mjs --headless

echo "===== ACCUMULATE — keep every portal's full set ====="
$NODE scripts/scan/accumulate.mjs 2>&1 | tail -3

echo "===== SCORE + TAILOR ====="
$NODE scripts/scan/process-scans.mjs 2>&1 | tail -2
# DISABLED 2026-10-14 per Nikhil ("no need company wise folder — i need only sheet hyderabad and
# naukri sheet under date wise folder"): no per-company tailored PDFs are generated by the
# automation any more. reports_stats/<date>/ keeps HYDERABAD.xlsx + NAUKRI.xlsx only.
# Manual /jd résumés are unaffected (they still go to ~/main/profile/manual/<Company>/).
# $NODE scripts/resume/gen-pass-pdfs.mjs 2>&1 | tail -2

echo "===== HYDERABAD SHEET + TRACKER ====="
$NODE scripts/scan/accumulate.mjs >/dev/null 2>&1   # push the new scores into the durable sidecar
$NODE scripts/sheets/build-hyderabad-sheet.mjs 2>&1 | tail -2
$NODE scripts/sheets/build-tracker.mjs 2>&1 | tail -2   # date-wise application tracker

OUT="reports_stats/$(date +%F)/HYDERABAD.xlsx"
TRK="reports_stats/$(date +%F)/TRACKER.xlsx"
echo
echo "✅ Done. Hyderabad sheet: $OUT"
echo "         Tracker:  $TRK"
[ "$(uname)" = "Darwin" ] && [ -f "$OUT" ] && open "$OUT"
