#!/bin/bash
# scan-dispatcher.sh — the "when the Mac is on, everything runs" engine.
#
# The problem it solves: macOS launchd does NOT replay calendar jobs that were
# missed while the Mac was asleep or powered off. So if the Mac is off at 07:00,
# the morning scan is lost forever and the sheets stay empty.
#
# This dispatcher is launched every 30 min AND at login/wake (RunAtLoad). On each
# run it checks the three daily review slots (morning/afternoon/night). For any
# slot whose time has already passed today and that has NOT yet run, it runs the
# full scan batch and drops a marker so it never double-runs. Result: open the
# laptop any time after 07:00 and the morning slot fires within ~30 min (or
# instantly on login).
#
# Disable anytime:
#   launchctl unload ~/Library/LaunchAgents/com.nikhil.careerops-dispatcher.plist

REPO="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")/../.." && pwd)"   # repo root, wherever this is cloned
cd "$REPO" || exit 1
export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"

NODE=/opt/homebrew/bin/node
LOG=data/dispatcher.log
MARKDIR=data/.dispatch
mkdir -p "$MARKDIR" data

TODAY=$(date +%F)
NOW_MIN=$(( 10#$(date +%H) * 60 + 10#$(date +%M) ))

# --- Naukri profile/résumé refresh: PERMANENTLY DISABLED (per user 2026-08-12,
# reaffirmed 2026-08-14: "stop updating the resume" is the ONLY thing that stays
# off — job scanning/notifications resume as default). Do NOT re-add a call to
# naukri-refresh(-strict).mjs/.sh here without an explicit new user request.

# slot name -> start minute-of-day. A slot is "due" once NOW is past its start.
run_slot() {
  local slot=$1 start=$2
  local mark="$MARKDIR/$TODAY-$slot"
  [ "$NOW_MIN" -lt "$start" ] && return 0          # not time yet today
  [ -f "$mark" ] && return 0                       # already ran this slot today

  echo "===== $(date) dispatcher: running slot '$slot' =====" >> "$LOG"

  # 1) LinkedIn scan (module01)
  bash scripts/pipelines/daily-devops.sh >> data/devops-scan.log 2>&1
  # 2) Naukri job scan (module04) — notification/scan only. Naukri PROFILE/résumé
  # refresh stays permanently disabled (see top of file) — do not re-add it here.
  "$NODE" scripts/scan/scan-naukri.mjs --headless >> data/naukri-scan.log 2>&1
  # PORTAL SET (per user 2026-07-23): ONLY the portals we can genuinely scan —
  # LinkedIn, Naukri, Google (Hyderabad pipeline), Indeed, Hirist, Instahyre.
  # Removed: remote boards, SimplyHired, Cutshort, Wellfound, Foundit, NodeFlair.
  # 4) Indeed (module11) — real Chrome, homepage-first to clear Cloudflare.
  # --days=1 = strict last-24h (per user 2026-08-17 "no compromise" audit — matches
  # LinkedIn's f_TPR=r86400 and Naukri's default 1-day window). Cloudflare walls this
  # intermittently in headless mode; best-effort — a wall here never blocks the rest.
  "$NODE" scripts/scan/scan-indeed.mjs --headless --days=1 >> data/indeed-scan.log 2>&1
  # 5) Hirist (module05) — real Chrome, DevOps-focused India board
  "$NODE" scripts/scan/scan-hirist.mjs --headless >> data/hirist-scan.log 2>&1
  # 6) Instahyre (module03) — real Chrome, matched-feed India board
  "$NODE" scripts/scan/scan-instahyre.mjs --headless >> data/instahyre-scan.log 2>&1
  # 10) ACCUMULATE — keep every portal's full job set across runs (nothing disappears)
  "$NODE" scripts/scan/accumulate.mjs >> data/auto-process.log 2>&1
  # 11) FAST deterministic scoring — ATS + JD-fit + insight for every job that has a JD/skills
  "$NODE" scripts/scan/process-scans.mjs >> data/auto-process.log 2>&1
  # 12) AGENT pass — fills the rest (jobs with no JD → WebFetch + score) + web-searches walled boards.
  bash scripts/pipelines/auto-process.sh
  # 13) résumé generation — RESTORED (per user 2026-08-16, reverting the 2026-08-12/08-14
  # opt-out): build a tailored PDF for every job that just cleared pass=true, deduped
  # per company per day. Keep output/cv-content.json synced to the base first — it's the
  # source tailor-resume.mjs/build-resume.mjs build from, and it silently goes stale.
  cp data/resume-base.content.json output/cv-content.json
  # DISABLED 2026-10-14 per Nikhil ("no need company wise folder — i need only sheet hyderabad and
  # naukri sheet under date wise folder"): no per-company tailored PDFs are generated by the
  # automation any more. reports_stats/<date>/ keeps HYDERABAD.xlsx + NAUKRI.xlsx only.
  # Manual /jd résumés are unaffected (they still go to ~/main/profile/manual/<Company>/).
  # "$NODE" scripts/resume/gen-pass-pdfs.mjs >> data/auto-process.log 2>&1
  # 14) push fresh scores + résumé paths into the durable sidecar, then build the outputs
  "$NODE" scripts/scan/accumulate.mjs >> data/auto-process.log 2>&1
  # 15) MASTER workbook (tab per portal) + date-wise TRACKER (applied / ready-to-apply)
  # master sheet REMOVED per user 2026-07-25 — HYDERABAD.xlsx is the only jobs sheet
  "$NODE" scripts/sheets/build-tracker.mjs >> data/master-sheet.log 2>&1

  touch "$mark"
  echo "===== $(date) dispatcher: slot '$slot' done =====" >> "$LOG"
}

run_slot morning   420    # 07:00
run_slot afternoon 840    # 14:00
run_slot night     1200   # 20:00

# --- Hyderabad openings catch-up (per user 2026-07-17) ---------------------
# The com.nikhil.careerops-hyderabad launchd job runs this at 10:00/17:00/22:00,
# but launchd does not replay slots missed while the Mac was SHUT DOWN. This
# replays any passed-and-unmarked slot within 30 min of the Mac coming back.
# The pipeline touches data/.dispatch/<date>-hyd-<slot> itself on success.
run_hyd_slot() {
  local slot=$1 start=$2
  local mark="$MARKDIR/$TODAY-hyd-$slot"
  [ "$NOW_MIN" -lt "$start" ] && return 0
  [ -f "$mark" ] && return 0
  echo "===== $(date) dispatcher: hyderabad catch-up slot '$slot' =====" >> "$LOG"
  HYD_SLOT="$slot" bash scripts/pipelines/hyderabad-openings.sh >> data/hyderabad-openings.log 2>&1
}
run_hyd_slot 03:00 180
run_hyd_slot 08:00 480
run_hyd_slot 18:00 1080
run_hyd_slot 20:00 1200
