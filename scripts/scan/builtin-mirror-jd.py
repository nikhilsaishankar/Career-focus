import re,json,subprocess,sys
def text(h):
    h=re.sub(r'(?is)<(script|style|noscript)[^>]*>.*?</\1>',' ',h)
    h=re.sub(r'(?i)<br\s*/?>|</p>|</li>|</div>|</h\d>','\n',h)
    t=re.sub(r'(?s)<[^>]+>',' ',h)
    import html as H; t=H.unescape(t)
    t=re.sub(r'[ \t\xa0]+',' ',t)
    return [l.strip() for l in t.split('\n')]
END=re.compile(r'(Popular Tech Hubs|Read Full Description|What the Team is Saying|'
               r'Similar Jobs|All Jobs at|Am I A Good Fit)',re.I)
def jd_of(url):
    h=subprocess.run(["curl","-sL","-A","Mozilla/5.0","-m","35",url],
                     capture_output=True,text=True).stdout
    L=text(h)
    nz=[(i,l) for i,l in enumerate(L) if l]
    start=None
    for k,(i,l) in enumerate(nz):
        if l.startswith("The Role"): start=k+1; break
        if "summary above was generated by AI" in l: start=max(0,k-1); break
    if start is None: start=0
    body=[]
    for i,l in nz[start:]:
        if END.search(l): break
        body.append(l)
    # company: ld+json JobPosting or hiringOrganization
    comp=""
    m=re.search(r'"hiringOrganization"\s*:\s*\{[^}]*?"name"\s*:\s*"([^"]+)"',h)
    if m: comp=m.group(1)
    loc=""
    m=re.search(r'"addressLocality"\s*:\s*"([^"]+)"',h)
    if m: loc=m.group(1)
    sen=""
    m=re.search(r'\b(Entry level|Junior|Mid level|Senior level)\b',"\n".join(nz_l for _,nz_l in nz[:start+3]) if start else "\n".join(l for _,l in nz[:40]))
    if m: sen=m.group(1)
    return "\n".join(body), comp, loc, sen, len(h)
if __name__=="__main__":
    cands=json.load(open(sys.argv[1]))
    n=int(sys.argv[2]) if len(sys.argv)>2 else 40
    out=[]
    for r in cands[:n]:
        jd,comp,loc,sen,sz=jd_of(r["url"])
        r2=dict(r); r2.update(jd=jd,company=comp,loc=loc,seniority=sen,pagesize=sz)
        out.append(r2)
        print(f'{r["prefix"]}-{r["id"]} jdlen={len(jd)} comp={comp[:34]!r} loc={loc[:22]!r} sen={sen} | {r["title"][:40]}',file=sys.stderr)
    json.dump(out,open("/tmp/bi/jds.json","w"),indent=1)
